#!/usr/bin/env python3
"""Convert an Overpass GeoJSON export into roads-local.js (const LOCAL_ROADS = [{c, t, p}])."""
import json, sys
RANK = {"motorway": "major", "trunk": "major", "primary": "sec", "secondary": "sec"}
roads = []
for f in json.load(open(sys.argv[1]))["features"]:
    g = f["geometry"]
    if g["type"] != "LineString": continue
    p = f["properties"]
    roads.append({"c": p.get("ref", ""), "t": RANK.get(p.get("highway"), "road"),
                  "p": [[round(x, 5), round(y, 5)] for x, y in g["coordinates"]]})
print("// generated by tools/convert-roads.py\nconst LOCAL_ROADS = " + json.dumps(roads, separators=(",", ":")) + ";")
